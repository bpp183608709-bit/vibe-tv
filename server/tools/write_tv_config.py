"""Write the television's build-time quiz configuration from the keys already on this machine.

    python3 -m server.tools.write_tv_config --base-url https://203.0.113.9:8443

Reads `server/local/ticket-signing-key.pem` (from `server/tools/genkey.py`) and writes
`local/quiz.properties`, which `app/build.gradle.kts` turns into three BuildConfig fields:

    baseUrl   where the server is, scheme included; https only
    publicKey the ES256 ticket key, base64 SPKI — one half of a key pair, useless for signing
    devHmac   left empty on purpose; see below

The file lands in `local/`, which is gitignored: the address of a household's server does not belong
in a public repository, and neither does anything about its keys.

**No `devHmac` is written.** That field exists so a build with no server certificate can still be
tested against a development HMAC key; a build that has an ES256 key never accepts an HS256 ticket
(see `QuizTicket.verify`), so filling both in would only make the settings file lie about what the
APK can do.
"""

from __future__ import annotations

import argparse
import base64
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent.parent))

from server.app import es256  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write local/quiz.properties for the TV build.")
    parser.add_argument("--base-url", required=True, help="e.g. https://203.0.113.9:8443")
    parser.add_argument("--key", default="server/local/ticket-signing-key.pem")
    parser.add_argument("--out", default="local/quiz.properties")
    args = parser.parse_args(argv)

    if not args.base_url.startswith("https://"):
        print("the television only talks https; give a https:// address", file=sys.stderr)
        return 2

    key_path = pathlib.Path(args.key).expanduser()
    if not key_path.exists():
        print(f"{key_path} not found; run: python3 -m server.tools.genkey --out server/local", file=sys.stderr)
        return 1

    public_point = es256.load_public_pem(es256.public_to_pem(
        es256.public_point(es256.load_private_pem(key_path.read_bytes()))
    ))
    # The 64 raw bytes of X||Y, base64: 88 characters instead of a whole PEM in a BuildConfig line.
    raw = es256.public_raw(public_point)
    public_b64 = base64.b64encode(raw).decode("ascii")

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# Generated by server/tools/write_tv_config.py — gitignored (local/).\n"
        f"baseUrl={args.base_url}\n"
        f"publicKey={public_b64}\n",
        encoding="utf-8",
    )
    print(f"wrote {out}: baseUrl={args.base_url}, publicKey=<{len(raw)} bytes>")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
