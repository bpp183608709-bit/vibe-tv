"""Ask a running server for a real ticket and write it out as a test vector for the television.

    python3 -m server.tools.make_tv_fixture --base-url https://127.0.0.1:8443 \
        --cacert server/local/tls/ca.pem

Writes `app/src/test/resources/quiz-ticket.json`, which `ServerTicketInteropTest` reads and checks:
the ticket the server signed must verify under the key the APK would carry, for the device and day it
was issued to. That is the one claim this project makes about its own security — *the server decides,
the television only verifies* — and it is worth a test that crosses the language boundary rather
than two test suites each agreeing with itself.

The answers are taken from the questions themselves (the server sends them, G2), so the run does not
depend on any particular question bank. Five right answers is the 80% pass line with room to spare.

Nothing here is needed at runtime. It is a build-time check, like `interop_es256.py`.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import ssl
import sys
import urllib.request

#: A fixed instant and day, so the fixture does not change every time it is regenerated. The 04:00
#: roll-over means this is the evening of the previous civil day; that is what the ticket carries.
FIXED_NOW_MS = 1_762_000_000_000
FIXED_DAY = "2026-11-13"


def call(base_url: str, path: str, body: dict, context: ssl.SSLContext) -> dict:
    data = json.dumps(body).encode("utf-8")
    request = urllib.request.Request(
        base_url.rstrip("/") + path,
        data=data,
        headers={"Content-Type": "application/json", "Accept": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, context=context, timeout=15) as response:
        return json.loads(response.read().decode("utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Record a server-signed ticket as a TV test vector.")
    parser.add_argument("--base-url", default="https://127.0.0.1:8443")
    parser.add_argument("--cacert", default="server/local/tls/ca.pem")
    parser.add_argument("--out", default="app/src/test/resources/quiz-ticket.json")
    parser.add_argument("--now-ms", type=int, default=FIXED_NOW_MS)
    parser.add_argument("--day", default=FIXED_DAY)
    args = parser.parse_args(argv)

    context = ssl.create_default_context(cafile=args.cacert)
    now = args.now_ms

    paired = call(args.base_url, "/v1/pair/start", {"name": "fixture", "now_ms": now}, context)
    device = paired["device_id"]

    served = call(args.base_url, "/v1/quiz/next", {"device_id": device, "day_key": args.day, "now_ms": now}, context)
    answers = []
    for question in served["questions"]:
        if question["qtype"] == "choice":
            chosen = next(option["label"] for option in question["options"] if option["correct"])
        else:
            chosen = question["accepted"][0]
        answers.append({"question_id": question["id"], "chosen": chosen, "flagged_unknown": False})

    graded = call(
        args.base_url,
        f"/v1/quiz/{served['session_id']}/grade",
        {"device_id": device, "answers": answers, "now_ms": now},
        context,
    )
    if not graded.get("passed") or not graded.get("ticket"):
        print(f"the server did not issue a ticket: {graded}", file=sys.stderr)
        return 1

    # The key the APK carries, in the same shape `write_tv_config.py` writes it.
    from server.app import es256

    private_key = es256.load_private_pem(pathlib.Path("server/local/ticket-signing-key.pem").read_bytes())
    public_raw = es256.public_raw(es256.public_point(private_key))

    import base64

    fixture = {
        "note": "Generated by server/tools/make_tv_fixture.py — a ticket this server really signed.",
        "device_id": device,
        "day_key": args.day,
        "now_ms": now,
        "public_key_b64": base64.b64encode(public_raw).decode("ascii"),
        "ticket": graded["ticket"],
    }
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(fixture, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out}: device {device}, award {graded['award_ms']} ms")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
