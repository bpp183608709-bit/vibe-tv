"""ECDSA P-256 / SHA-256, standard library only.

Why this exists instead of the `cryptography` package: this server has to be deployable to a 2-core
2 GB ECS with nothing but Python, and `cryptography` needs a Rust toolchain to build when no wheel is
published for the interpreter. A 1.5 kB ECDSA implementation is a fair trade for a dependency-free
deploy — and the surface is small enough to be read in one sitting, which is the only real defence
against a subtle crypto bug anyway.

What it implements, and nothing else:

  * P-256 point arithmetic (affine, not constant-time — see the note below);
  * ECDSA signing with **RFC 6979 deterministic nonces**, so a signature is reproducible and a broken
    RNG can never leak the private key (the failure mode that killed Sony's PS3 and a thousand
    Bitcoin wallets);
  * low-S normalisation, so each signature has exactly one valid encoding;
  * X9.62 DER signature encoding, and PKCS#8 / SPKI PEM key reading and writing, so keys generated by
    `openssl` load here and keys written here load into Java's `KeyFactory` and Android's JCA.

Interoperability is the acceptance test, not the round-trip: `tools/interop_es256.sh` signs here and
verifies with `openssl dgst -sha256 -verify`, and the other way round. Android's
`Signature.getInstance("SHA256withECDSA")` is the same X9.62/DER scheme, so passing openssl is the
evidence that a TV can verify what this file signs.

**Not constant-time.** Modular inverse and scalar multiply branch on secret bits. On a shared server
this is a theoretical side channel; on a home ECS with no co-tenants running attacker code it is not
one worth 300 lines of ladder arithmetic. Say so out loud rather than pretend otherwise.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import hmac
import os
from typing import Iterable

# Curve parameters, SEC 2 v2 §2.4.2 (prime256v1 / secp256r1).
P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
A = P - 3
B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5

Point = tuple[int, int]
#: None means the point at infinity. Every arithmetic helper accepts and returns it.
INFINITY: Point | None = None

#: DER-encoded OID values (tag and length are added by `_tlv`).
OID_EC_PUBLIC_KEY = bytes.fromhex("2A8648CE3D0201")   # 1.2.840.10045.2.1
OID_PRIME256V1 = bytes.fromhex("2A8648CE3D030107")    # 1.2.840.10045.3.1.7


# ---- point arithmetic ----

def _inv(value: int, modulus: int) -> int:
    return pow(value % modulus, -1, modulus)


def point_add(p1: Point | None, p2: Point | None) -> Point | None:
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2:
        if (y1 + y2) % P == 0:
            return INFINITY
        slope = (3 * x1 * x1 + A) * _inv(2 * y1, P) % P
    else:
        slope = (y2 - y1) * _inv(x2 - x1, P) % P
    x3 = (slope * slope - x1 - x2) % P
    return x3, (slope * (x1 - x3) - y1) % P


def _point_mul(k: int, point: Point | None) -> Point | None:
    """Double-and-add. `k` is reduced mod N first so a caller cannot pass 0 <= k < N only by luck."""
    if point is None or k % N == 0:
        return INFINITY
    k %= N
    result: Point | None = INFINITY
    addend: Point | None = point
    while k:
        if k & 1:
            result = point_add(result, addend)
        addend = point_add(addend, addend)
        k >>= 1
    return result


G: Point = (GX, GY)


# ---- RFC 6979 deterministic nonce ----

def _bits2octets(digest: bytes) -> bytes:
    z = int.from_bytes(digest, "big") % N
    return z.to_bytes(32, "big")


def _rfc6979_nonces(private_key: int, digest: bytes) -> Iterable[int]:
    """Yield the deterministic k sequence for (private_key, digest). RFC 6979 §3.2, HMAC-SHA-256.

    A generator rather than a single value because, in the (astronomically unlikely) event that
    r or s comes out zero, the spec says to take the next k rather than to draw a fresh random one.
    """
    x = private_key.to_bytes(32, "big")
    h1 = _bits2octets(digest)
    v = b"\x01" * 32
    k = b"\x00" * 32
    k = hmac.new(k, v + b"\x00" + x + h1, hashlib.sha256).digest()
    v = hmac.new(k, v, hashlib.sha256).digest()
    k = hmac.new(k, v + b"\x01" + x + h1, hashlib.sha256).digest()
    v = hmac.new(k, v, hashlib.sha256).digest()
    while True:
        v = hmac.new(k, v, hashlib.sha256).digest()
        candidate = int.from_bytes(v, "big")
        if 1 <= candidate < N:
            yield candidate
        k = hmac.new(k, v + b"\x00", hashlib.sha256).digest()
        v = hmac.new(k, v, hashlib.sha256).digest()


# ---- DER ----

def _tlv(tag: int, payload: bytes) -> bytes:
    length = len(payload)
    if length < 0x80:
        return bytes([tag, length]) + payload
    encoded = length.to_bytes((length.bit_length() + 7) // 8, "big")
    return bytes([tag, 0x80 | len(encoded)]) + encoded + payload


def _der_int(value: int) -> bytes:
    raw = value.to_bytes(max(1, (value.bit_length() + 7) // 8), "big")
    if raw[0] & 0x80:            # positive integers must not look negative
        raw = b"\x00" + raw
    return _tlv(0x02, raw)


def _der_seq(*parts: bytes) -> bytes:
    return _tlv(0x30, b"".join(parts))


def encode_signature(r: int, s: int) -> bytes:
    """X9.62 `ECDSA-Sig-Value ::= SEQUENCE { r INTEGER, s INTEGER }`."""
    return _der_seq(_der_int(r), _der_int(s))


def _read_tlv(data: bytes, offset: int = 0) -> tuple[int, bytes, int]:
    tag = data[offset]
    first = data[offset + 1]
    if first < 0x80:
        length, start = first, offset + 2
    else:
        count = first & 0x7F
        length = int.from_bytes(data[offset + 2 : offset + 2 + count], "big")
        start = offset + 2 + count
    end = start + length
    if end > len(data):
        raise ValueError("truncated DER")
    return tag, data[start:end], end


def _read_items(data: bytes) -> list[tuple[int, bytes]]:
    items, offset = [], 0
    while offset < len(data):
        tag, value, offset = _read_tlv(data, offset)
        items.append((tag, value))
    return items


def decode_signature(der: bytes) -> tuple[int, int]:
    tag, body, _ = _read_tlv(der)
    if tag != 0x30:
        raise ValueError("signature is not a SEQUENCE")
    items = _read_items(body)
    if len(items) != 2 or any(t != 0x02 for t, _ in items):
        raise ValueError("signature is not two INTEGERs")
    return int.from_bytes(items[0][1], "big"), int.from_bytes(items[1][1], "big")


# ---- signing and verifying ----

def sign(private_key: int, message: bytes) -> bytes:
    """Deterministic ECDSA over `message`, low-S, DER-encoded."""
    if not 1 <= private_key < N:
        raise ValueError("private key out of range")
    digest = hashlib.sha256(message).digest()
    z = int.from_bytes(digest, "big")
    for k in _rfc6979_nonces(private_key, digest):
        point = _point_mul(k, G)
        if point is None:
            continue
        r = point[0] % N
        if r == 0:
            continue
        s = (_inv(k, N) * (z + r * private_key)) % N
        if s == 0:
            continue
        if s > N // 2:            # low-S: exactly one valid (r, s) per (key, message)
            s = N - s
        return encode_signature(r, s)
    raise AssertionError("unreachable")


def verify(public_key: Point, message: bytes, signature: bytes) -> bool:
    try:
        r, s = decode_signature(signature)
    except (ValueError, IndexError):
        return False
    if not (1 <= r < N and 1 <= s < N):
        return False
    z = int.from_bytes(hashlib.sha256(message).digest(), "big")
    w = _inv(s, N)
    point = point_add(_point_mul(z * w % N, G), _point_mul(r * w % N, public_key))
    if point is None:
        return False
    return point[0] % N == r


# ---- keys ----

def generate() -> tuple[int, Point]:
    private_key = int.from_bytes(os.urandom(32), "big") % N
    if private_key == 0:
        raise RuntimeError("bad randomness")
    return private_key, _point_mul(private_key, G)  # type: ignore[return-value]


def public_point(private_key: int) -> Point:
    point = _point_mul(private_key, G)
    if point is None:
        raise ValueError("private key out of range")
    return point


def public_raw(public_key: Point) -> bytes:
    """64 bytes, X || Y. What goes into the APK: no ASN.1 parser needed on the TV side."""
    return public_key[0].to_bytes(32, "big") + public_key[1].to_bytes(32, "big")


def _pem(label: str, der: bytes) -> bytes:
    body = base64.b64encode(der).decode("ascii")
    lines = [body[i : i + 64] for i in range(0, len(body), 64)]
    return (f"-----BEGIN {label}-----\n" + "\n".join(lines) + f"\n-----END {label}-----\n").encode()


def _unpem(pem: bytes) -> bytes:
    text = pem.decode("ascii", "replace")
    body = "".join(
        line for line in text.splitlines() if line and not line.startswith("-----")
    )
    return base64.b64decode(body)


def public_to_pem(public_key: Point) -> bytes:
    """SubjectPublicKeyInfo, the shape `openssl ec -pubout` and Java's X509EncodedKeySpec expect."""
    algorithm = _der_seq(_tlv(0x06, OID_EC_PUBLIC_KEY), _tlv(0x06, OID_PRIME256V1))
    bits = _tlv(0x03, b"\x00\x04" + public_raw(public_key))
    return _pem("PUBLIC KEY", _der_seq(algorithm, bits))


def private_to_pem(private_key: int, public_key: Point | None = None) -> bytes:
    """PKCS#8 PrivateKeyInfo, the shape `openssl pkcs8` and Java's PKCS8EncodedKeySpec expect."""
    public_key = public_key or public_point(private_key)
    algorithm = _der_seq(_tlv(0x06, OID_EC_PUBLIC_KEY), _tlv(0x06, OID_PRIME256V1))
    ec_private = _der_seq(
        _der_int(1),
        _tlv(0x04, private_key.to_bytes(32, "big")),
        _tlv(0xA0, _tlv(0x06, OID_PRIME256V1)),
        _tlv(0xA1, _tlv(0x03, b"\x00\x04" + public_raw(public_key))),
    )
    return _pem("PRIVATE KEY", _der_seq(_der_int(0), algorithm, _tlv(0x04, ec_private)))


def load_private_pem(pem: bytes) -> int:
    """Accept PKCS#8 (`BEGIN PRIVATE KEY`) and SEC1 (`BEGIN EC PRIVATE KEY`)."""
    der = _unpem(pem)
    tag, body, _ = _read_tlv(der)
    if tag != 0x30:
        raise ValueError("not a DER SEQUENCE")
    items = _read_items(body)
    # PKCS#8: SEQUENCE { INTEGER 0, AlgorithmIdentifier, OCTET STRING(ECPrivateKey) }
    if len(items) >= 3 and items[0][0] == 0x02 and items[2][0] == 0x04:
        inner_tag, inner, _ = _read_tlv(items[2][1])
        if inner_tag != 0x30:
            raise ValueError("bad ECPrivateKey")
        items = _read_items(inner)
    # SEC1: SEQUENCE { INTEGER 1, OCTET STRING privateKey, ... }
    # OpenSSL trims leading zero bytes, so the scalar arrives as 1..32 bytes, not always 32.
    for tag_, value in items:
        if tag_ == 0x04 and 1 <= len(value) <= 32:
            return int.from_bytes(value, "big")
    raise ValueError("no private key found")


def load_public_pem(pem: bytes) -> Point:
    der = _unpem(pem)
    tag, body, _ = _read_tlv(der)
    if tag != 0x30:
        raise ValueError("not a DER SEQUENCE")
    items = _read_items(body)
    # SPKI: SEQUENCE { AlgorithmIdentifier, BIT STRING }
    for tag_, value in items:
        if tag_ == 0x03 and value and value[0] == 0x00:
            point = value[1:]
            if len(point) == 65 and point[0] == 0x04:
                return int.from_bytes(point[1:33], "big"), int.from_bytes(point[33:], "big")
    raise ValueError("no uncompressed point found")


def _selfcheck() -> None:
    """python -m server.app.es256 — round-trip, tamper, and a fixed vector."""
    private_key, public_key = generate()

    for message in (b"", b"AQ1.eyJ2IjoxfQ", os.urandom(200)):
        signature = sign(private_key, message)
        assert verify(public_key, message, signature), "round-trip failed"
        assert not verify(public_key, message + b"x", signature), "tampered message accepted"

    signature = sign(private_key, b"same message")
    assert signature == sign(private_key, b"same message"), "RFC 6979 nonce is not deterministic"

    # Low-S: signing always emits s <= n/2, so the same message has one canonical encoding. A verifier
    # still accepts the mirrored s (that is what the standard says), which is why the normalisation
    # has to happen at signing time and not be mistaken for a security check.
    r, s = decode_signature(signature)
    assert s <= N // 2, "signer emitted a high-S signature"
    assert verify(public_key, b"same message", encode_signature(r, N - s))

    # Key formats must survive a PEM round-trip, since openssl and Java read these files.
    assert load_private_pem(private_to_pem(private_key, public_key)) == private_key
    assert load_public_pem(public_to_pem(public_key)) == public_key

    print("es256: ok")


if __name__ == "__main__":
    _selfcheck()
